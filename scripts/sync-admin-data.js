/**
 * Sync admin JSON data into the source .js config files used by the site and build.
 * Run after editing content in the admin panel so the static site uses the new data.
 *
 * Usage: node scripts/sync-admin-data.js
 *
 * Reads:  data/index-content.json, data/typeface-detail-content.json
 * Writes: typefaces-data.js, typeface-detail-data.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const INDEX_JSON = path.join(ROOT, 'data', 'index-content.json');
const DETAIL_JSON = path.join(ROOT, 'data', 'typeface-detail-content.json');
const TYPEFACES_JS = path.join(ROOT, 'typefaces-data.js');
const DETAIL_JS = path.join(ROOT, 'typeface-detail-data.js');

function escapeJsString(s) {
  if (typeof s !== 'string') return s;
  return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n').replace(/\r/g, '\\r');
}

function formatValue(v, indent) {
  const sp = '  '.repeat(indent);
  if (v === null) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'string') return "'" + escapeJsString(v) + "'";
  if (Array.isArray(v)) {
    if (v.length === 0) return '[]';
    const items = v.map((item) => sp + '    ' + formatValue(item, indent + 2)).join(',\n');
    return '[\n' + items + '\n' + sp + ']';
  }
  if (typeof v === 'object') {
    const keys = Object.keys(v);
    if (keys.length === 0) return '{}';
    const pairs = keys.map((k) => sp + '    ' + k + ': ' + formatValue(v[k], indent + 2)).join(',\n');
    return '{\n' + pairs + '\n' + sp + '}';
  }
  return 'null';
}

function writeTypefacesDataJs(arr) {
  const lines = [
    '/**',
    ' * Typeface configuration data',
    ' * Used to generate typeface sections dynamically',
    ' * Generated by scripts/sync-admin-data.js from data/index-content.json',
    ' */',
    '',
    'const typefacesConfig = [',
  ];
  arr.forEach((item, i) => {
    const pairs = Object.keys(item).map((k) => '        ' + k + ': ' + formatValue(item[k], 2)).join(',\n');
    lines.push('    {');
    lines.push(pairs);
    lines.push('    }' + (i < arr.length - 1 ? ',' : ''));
  });
  lines.push('];');
  lines.push('');
  lines.push('if (typeof window !== \'undefined\') window.typefacesConfig = typefacesConfig;');
  lines.push('if (typeof module !== \'undefined\' && module.exports) module.exports = { typefacesConfig };');
  lines.push('');
  fs.writeFileSync(TYPEFACES_JS, lines.join('\n'), 'utf8');
}

function writeTypefaceDetailDataJs(obj) {
  const lines = [
    '/**',
    ' * Typeface detail page configuration',
    ' * Contains descriptions, sample texts, technical details, and pricing for each typeface',
    ' * Generated by scripts/sync-admin-data.js from data/typeface-detail-content.json',
    ' */',
    '',
    'const typefaceDetailConfig = {',
  ];
  const ids = Object.keys(obj);
  ids.forEach((id, i) => {
    const item = obj[id];
    const pairs = Object.keys(item).map((k) => '        ' + k + ': ' + formatValue(item[k], 2)).join(',\n');
    lines.push("    '" + escapeJsString(id) + "': {");
    lines.push(pairs);
    lines.push('    }' + (i < ids.length - 1 ? ',' : ''));
  });
  lines.push('};');
  lines.push('');
  lines.push('if (typeof module !== \'undefined\' && module.exports) module.exports = { typefaceDetailConfig };');
  lines.push('');
  fs.writeFileSync(DETAIL_JS, lines.join('\n'), 'utf8');
}

function main() {
  if (!fs.existsSync(INDEX_JSON)) {
    console.error('Missing data/index-content.json. Create it or run the admin and save index content once.');
    process.exit(1);
  }
  if (!fs.existsSync(DETAIL_JSON)) {
    console.error('Missing data/typeface-detail-content.json. Create it or run the admin and save detail content once.');
    process.exit(1);
  }
  const indexContent = JSON.parse(fs.readFileSync(INDEX_JSON, 'utf8'));
  const detailContent = JSON.parse(fs.readFileSync(DETAIL_JSON, 'utf8'));
  if (!Array.isArray(indexContent)) {
    console.error('data/index-content.json must be a JSON array.');
    process.exit(1);
  }
  if (typeof detailContent !== 'object' || Array.isArray(detailContent)) {
    console.error('data/typeface-detail-content.json must be a JSON object.');
    process.exit(1);
  }
  writeTypefacesDataJs(indexContent);
  writeTypefaceDetailDataJs(detailContent);
  console.log('Synced typefaces-data.js and typeface-detail-data.js from admin JSON.');
}

main();
